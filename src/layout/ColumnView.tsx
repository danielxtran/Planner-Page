import { useDroppable } from '@dnd-kit/core'
import { SortableContext, verticalListSortingStrategy } from '@dnd-kit/sortable'
import type { CSSProperties, RefObject } from 'react'
import type { Column } from '../storage/pages'
import { AddWidgetMenu } from './AddWidgetMenu'
import { ColumnResizer } from './ColumnResizer'
import type { DragData, EditorActions } from './editorTypes'
import { WidgetFrame } from './WidgetFrame'

interface ColumnViewProps {
  column: Column
  /** The column to the right, if any; there's a resize divider between them. */
  next: Column | undefined
  rowId: string
  rowIndex: number
  columnIndex: number
  editing: boolean
  actions: EditorActions
  gridRef: RefObject<HTMLDivElement | null>
}

export function ColumnView(props: ColumnViewProps) {
  const { column, next, rowId, rowIndex, columnIndex, editing, actions, gridRef } = props
  const label = `column ${columnIndex + 1} of row ${rowIndex + 1}`
  const data: DragData = { type: 'column', label }
  // The column itself is a drop target too, so a widget can land in an empty column.
  const { setNodeRef, isOver } = useDroppable({ id: column.id, data, disabled: !editing })

  return (
    <div
      ref={setNodeRef}
      // Width comes from data, so it's a CSS variable: a class like `col-span-${n}`
      // built at runtime would never be generated by Tailwind.
      style={{ '--span': column.width } as CSSProperties}
      // Full width on phones; the saved twelfths apply from the md breakpoint up.
      className={`relative col-span-12 md:col-span-(--span) ${
        editing
          ? `min-h-28 rounded-sm border border-dashed p-2 ${isOver ? 'border-ink/50 bg-lavender/30' : 'border-ink/20'}`
          : ''
      }`}
    >
      {editing && (
        <p className="mb-2 text-xs text-ink-soft" aria-hidden>
          {column.width}/12
        </p>
      )}
      <SortableContext
        id={column.id}
        items={column.widgets.map((w) => w.id)}
        strategy={verticalListSortingStrategy}
      >
        <div className="space-y-4">
          {column.widgets.map((widget) => (
            <WidgetFrame
              key={widget.id}
              widget={widget}
              editing={editing}
              onRemove={() => actions.removeWidget(widget.id)}
            />
          ))}
        </div>
      </SortableContext>
      {editing && (
        <AddWidgetMenu label={label} onAdd={(type) => actions.addWidget(column.id, type)} />
      )}
      {editing && next && (
        <ColumnResizer
          leftWidth={column.width}
          rightWidth={next.width}
          gridRef={gridRef}
          label={`Resize columns ${columnIndex + 1} and ${columnIndex + 2} of row ${rowIndex + 1}`}
          onPreview={(delta) => actions.previewResize(rowId, columnIndex, delta)}
          onCommit={(delta) => actions.commitResize(rowId, columnIndex, delta)}
        />
      )}
    </div>
  )
}
