import { useDroppable } from '@dnd-kit/core'
import { SortableContext, verticalListSortingStrategy } from '@dnd-kit/sortable'
import {
  useEffect,
  useId,
  useRef,
  useState,
  type CSSProperties,
  type FocusEvent,
  type RefObject,
} from 'react'
import type { Column } from '../storage/pages'
import { AddWidgetMenu } from './AddWidgetMenu'
import { ColumnResizer } from './ColumnResizer'
import type { DragData, EditorActions } from './editorTypes'
import { WidgetFrame } from './WidgetFrame'

interface ColumnViewProps {
  column: Column
  /** The column to the right, if any; there's a resize divider between them. */
  next: Column | undefined
  rowId: string
  rowIndex: number
  columnIndex: number
  editing: boolean
  actions: EditorActions
  gridRef: RefObject<HTMLDivElement | null>
  /** Reports this column's natural content height, so the row can compare columns. */
  onMeasure: (columnId: string, height: number) => void
  /** Cut the column to this many px with a "Show more" button, or null to show it all. */
  collapseTo: number | null
}

export function ColumnView(props: ColumnViewProps) {
  const { column, next, rowId, rowIndex, columnIndex, editing, actions, gridRef } = props
  const { onMeasure, collapseTo } = props
  const label = `column ${columnIndex + 1} of row ${rowIndex + 1}`
  const data: DragData = { type: 'column', label }
  // The column itself is a drop target too, so a widget can land in an empty column.
  const { setNodeRef, isOver } = useDroppable({ id: column.id, data, disabled: !editing })
  const contentRef = useRef<HTMLDivElement>(null)
  const clipRef = useRef<HTMLDivElement>(null)
  const clipId = useId()
  const [expanded, setExpanded] = useState(false)
  const collapsed = collapseTo !== null && !expanded

  // Measure the content, not the clipped box around it, so cutting the column
  // never changes the number it's cut by (which would loop).
  useEffect(() => {
    const content = contentRef.current
    if (!content || typeof ResizeObserver === 'undefined') return
    const observer = new ResizeObserver(() => onMeasure(column.id, content.offsetHeight))
    observer.observe(content)
    return () => observer.disconnect()
  }, [column.id, onMeasure])

  // Tabbing to something hidden below the cut opens the column, so focus never lands out of sight.
  function handleFocus(e: FocusEvent<HTMLDivElement>) {
    const clip = clipRef.current
    if (!collapsed || !clip) return
    if (e.target.getBoundingClientRect().bottom > clip.getBoundingClientRect().bottom) {
      setExpanded(true)
    }
  }

  function showLess() {
    setExpanded(false)
    // If the top of the column is now off screen, bring it back into view.
    requestAnimationFrame(() => clipRef.current?.scrollIntoView({ block: 'nearest' }))
  }

  return (
    <div
      ref={setNodeRef}
      // Width comes from data, so it's a CSS variable: a class like `col-span-${n}`
      // built at runtime would never be generated by Tailwind.
      style={{ '--span': column.width } as CSSProperties}
      // Full width on phones; the saved twelfths apply from the md breakpoint up.
      // min-w-0: grid items otherwise grow to fit their widest content (a long
      // word, an embed), pushing the row's columns off their twelfths.
      className={`relative col-span-12 min-w-0 md:col-span-(--span) ${
        editing
          ? `min-h-28 rounded-sm border border-dashed p-2 ${isOver ? 'border-ink/50 bg-lavender/30' : 'border-ink/20'}`
          : ''
      }`}
    >
      {editing && (
        <p className="mb-2 text-xs text-ink-soft" aria-hidden>
          {column.width}/12
        </p>
      )}
      <SortableContext
        id={column.id}
        items={column.widgets.map((w) => w.id)}
        strategy={verticalListSortingStrategy}
      >
        <div
          ref={clipRef}
          id={clipId}
          onFocus={handleFocus}
          // overflow: clip (not hidden) hides the rest without making a scroll box.
          className={collapsed ? 'relative overflow-clip' : undefined}
          style={collapsed ? { maxHeight: collapseTo } : undefined}
        >
          <div ref={contentRef} className="space-y-4">
            {column.widgets.map((widget) => (
              <WidgetFrame
                key={widget.id}
                widget={widget}
                editing={editing}
                onRemove={() => actions.removeWidget(widget.id)}
              />
            ))}
          </div>
          {collapsed && (
            // A soft fade into the paper, so it's clear the column continues.
            <div
              aria-hidden
              className="pointer-events-none absolute inset-x-0 bottom-0 h-16 bg-linear-to-b from-transparent to-paper"
            />
          )}
        </div>
      </SortableContext>
      {collapseTo !== null && (
        <button
          type="button"
          aria-expanded={expanded}
          aria-controls={clipId}
          onClick={() => (expanded ? showLess() : setExpanded(true))}
          className="mt-2 w-full rounded-full border border-dashed border-ink/30 bg-card/80 py-1 text-sm text-ink-soft hover:bg-butter hover:text-ink"
        >
          {expanded ? 'Show less' : 'Show more'} <span aria-hidden>{expanded ? '▴' : '▾'}</span>
          <span className="sr-only"> of {label}</span>
        </button>
      )}
      {editing && (
        <AddWidgetMenu
          label={label}
          onAdd={(type, starter) => actions.addWidget(column.id, type, starter)}
        />
      )}
      {editing && next && (
        <ColumnResizer
          leftWidth={column.width}
          rightWidth={next.width}
          gridRef={gridRef}
          label={`Resize columns ${columnIndex + 1} and ${columnIndex + 2} of row ${rowIndex + 1}`}
          onPreview={(delta) => actions.previewResize(rowId, columnIndex, delta)}
          onCommit={(delta) => actions.commitResize(rowId, columnIndex, delta)}
        />
      )}
    </div>
  )
}
